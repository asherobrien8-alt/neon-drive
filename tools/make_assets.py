def grid(art):
    rows = [r for r in art.strip("\n").split("\n")]
    w = max(len(r) for r in rows)
    return [r.ljust(w, ".") for r in rows], w, len(rows)


def layer(art, chars):
    rows, w, h = grid(art)
    stride = (w + 7) // 8
    out = bytearray(stride * h)
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c in chars:
                out[y * stride + (x >> 3)] |= 0x80 >> (x & 7)
    return bytes(out), w, h


SPRITES = {
    # name: (art, layer chars)
    "car_b": (CAR, "B"),
    "car_d": (CAR, "D"),
    "car_n": (CAR, "N"),
    "palm":  (PALM, "N"),
    "run_a": (RUN_A, "BH"),
    "run_ah": (RUN_A, "H"),
    "run_b": (RUN_B, "BH"),
    "run_bh": (RUN_B, "H"),
}

PREVIEW_COL = {"B": (138, 124, 168), "D": (18, 10, 30), "N": (63, 240, 224),
               "H": (170, 255, 120)}


def main():
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(PREV, exist_ok=True)
    total = 0
    cfg = []
    for name, (art, chars) in SPRITES.items():
        data, w, h = layer(art, chars)
        assert w <= 64 and h <= 64 and (w + 7) // 8 <= 8, name
        with open(os.path.join(OUT, name + ".bin"), "wb") as f:
            f.write(data)
        total += len(data)
        cfg.append("asset_%s=assets/%s.bin,%d,%d" % (name, name, w, h))
    assert len(SPRITES) <= 8, "ReChord allows 8 assets"
    assert total <= 1024, "ReChord asset cache is 1 KiB (%d)" % total
    for nm, art in (("car", CAR), ("palm", PALM), ("run_a", RUN_A), ("run_b", RUN_B)):
        rows, w, h = grid(art)
        im = Image.new("RGB", (w, h), (20, 10, 34))
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                if c in PREVIEW_COL:
                    im.putpixel((x, y), PREVIEW_COL[c])
        im.resize((w * 8, h * 8), Image.NEAREST).save(os.path.join(PREV, nm + ".png"))
    print("\n".join(cfg))
    print("asset bytes: %d / 1024" % total)


if __name__ == "__main__":
    main()
